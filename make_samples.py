def check_rows(rows: list[dict]) -> None:
    if len(rows) < 40:
        raise SystemExit(f"Expected about 40 rows, got {len(rows)}")
    keys = [
        (
            r["raw_product"],
            r["raw_price"],
            r["customer_name"],
            r["phone"],
            r["address"],
            r["feedback"],
        )
        for r in rows
    ]
    if len(keys) - len(set(keys)) != 1:
        raise SystemExit("Sample should contain exactly one duplicate row")
    if sum(1 for r in rows if not str(r["raw_product"]).strip()) != 1:
        raise SystemExit("Sample should contain exactly one empty product")
    if sum(1 for r in rows if parse_price_vnd(r["raw_price"]) is None) != 1:
        raise SystemExit("Sample should contain exactly one unparseable price")
    if sum(1 for r in rows if normalize_phone(r["phone"]) is None) != 1:
        raise SystemExit("Sample should contain exactly one invalid phone")
    for item in rows:
        mock = item["mock"]
        if not mock["address"]["needs_review"] and not address_is_valid(mock["address"]["normalized"]):
            raise SystemExit(f"Mock address failed validation: {mock['address']['normalized']!r}")
    formats = {r["raw_price"] for r in rows}
    for expected in ("25.000đ", "25k", "25,000", "1tr2"):
        if expected not in formats:
            raise SystemExit(f"Missing price format {expected}")
    phones = {r["phone"] for r in rows}
    for expected in ("0912 345 678", "+84912345678", "912.345.678"):
        if expected not in phones:
            raise SystemExit(f"Missing phone format {expected}")


def write_xlsx(rows: list[dict], dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = "Du lieu goc"
    headers = ["raw_product", "raw_price", "customer_name", "phone", "address", "feedback"]
    ws.append(headers)
    for item in rows:
        ws.append([item[name] for name in headers])
        for col in range(1, 7):
            ws.cell(ws.max_row, col).number_format = "@"
    widths = [46, 14, 22, 18, 52, 42]
    for index, width in enumerate(widths, start=1):
        ws.column_dimensions[chr(64 + index)].width = width
    wb.save(dest)


def write_mock(rows: list[dict], dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    seen: set[tuple[str, str, str]] = set()
    payload_rows = []
    for item in rows:
        key = (item["raw_product"], item["address"], item["feedback"])
        if key in seen:
            continue
        seen.add(key)
        payload_rows.append(
            {
                "raw_product": item["raw_product"],
                "address": item["address"],
                "feedback": item["feedback"],
                "enrichment": item["mock"],
            }
        )
    payload = {
        "description": (
            "Bundled Gemini stand-in for --offline / --dry-run. "
            "Keyed by raw_product + address + feedback. Fictional shop data."
        ),
        "rows": payload_rows,
    }
    dest.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def main() -> None:
    rows = build_rows()
    check_rows(rows)
    write_xlsx(rows, SAMPLE_XLSX)
    write_mock(rows, MOCK_JSON)
    print(f"Đã ghi / Wrote {len(rows)} dòng / rows → {SAMPLE_XLSX}")
    print(f"Đã ghi mock / Wrote mock → {MOCK_JSON}")


